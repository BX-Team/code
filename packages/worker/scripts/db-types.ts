#!/usr/bin/env bun
// bx-db-types [migrations dir] [out file]: Kysely table types from an app's D1 migrations.
import { Database } from 'bun:sqlite';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { $ } from 'bun';

const [dir = 'migrations', out = 'src/tables.ts'] = process.argv.slice(2);

interface Column {
  name: string;
  type: string;
  notnull: number;
  dflt_value: string | null;
  pk: number;
}

const db = new Database(':memory:');
for (const file of readdirSync(dir)
  .filter(name => name.endsWith('.sql'))
  .sort())
  db.exec(readFileSync(join(dir, file), 'utf8'));

const tables = db
  .query<{ name: string; sql: string }, []>(
    `select name, sql from sqlite_master where type = 'table' and name not like 'sqlite_%' and name not like '_cf_%' order by name`,
  )
  .all();

const pascal = (name: string) => name.replace(/(^|[_-])(\w)/g, (_, __, ch: string) => ch.toUpperCase());

function base(type: string): string {
  const t = type.toLowerCase();
  if (t.includes('int') || t.includes('real') || t.includes('floa') || t.includes('doub') || t.includes('num'))
    return 'number';
  if (t.includes('blob')) return 'ArrayBuffer';
  return 'string';
}

/** `check ("col" in ('a', 'b'))` in the table's SQL narrows the column to those values. */
function choices(sql: string, column: string): string | null {
  const match = sql.match(new RegExp(`check\\s*\\(\\s*"?${column}"?\\s+in\\s*\\(([^)]*)\\)\\s*\\)`, 'i'));
  if (!match?.[1]) return null;
  const values = [...match[1].matchAll(/'((?:[^']|'')*)'/g)].map(m => `'${m[1]}'`);
  return values.length ? values.join(' | ') : null;
}

const lines = ['// Generated by bx-db-types from the D1 migrations; run `bun run db:types` after adding one.', ''];
for (const table of tables) {
  const columns = db.query<Column, []>(`pragma table_info("${table.name}")`).all();
  // Only a lone INTEGER PRIMARY KEY is the rowid, which SQLite fills in itself.
  const rowid =
    columns.filter(c => c.pk).length === 1 ? columns.find(c => c.pk && c.type.toUpperCase() === 'INTEGER') : undefined;
  lines.push(`export interface ${pascal(table.name)}Table {`);
  for (const column of columns) {
    let type = choices(table.sql, column.name) ?? base(column.type);
    const nullable = !column.notnull && !column.pk;
    if (nullable) type += ' | null';
    const generated = column.dflt_value != null || column === rowid;
    const key = /^[A-Za-z_$][\w$]*$/.test(column.name) ? column.name : `'${column.name}'`;
    lines.push(`  ${key}: ${generated ? `Generated<${type}>` : type};`);
  }
  lines.push('}', '');
}
lines.push('export interface Tables {');
for (const table of tables) {
  const key = /^[A-Za-z_$][\w$]*$/.test(table.name) ? table.name : `'${table.name}'`;
  lines.push(`  ${key}: ${pascal(table.name)}Table;`);
}
lines.push('}', '');
const text = lines.join('\n');
const header = text.includes('Generated<') ? `import type { Generated } from 'kysely';\n\n` : '';
writeFileSync(out, text.replace('\n\n', `\n\n${header}`));
// The same bytes Biome would write, so CI can tell a stale file by a diff.
await $`biome format --write ${out}`.quiet();
console.log(`${out}: ${tables.length} tables`);
