<script setup lang="ts">
import { Download } from '@lucide/vue';
import { computed, ref, watch } from 'vue';
import { syncQuery } from '@/lib/query';
import { build, VERIFIED_AGAINST } from '@/lib/serverconfig/build';
import { SOFTWARE_LABELS, type Software } from '@/lib/serverconfig/files';
import {
  DEFAULT_PROFILE,
  INTENSITIES,
  type Intensity,
  type Profile,
  type ProxyKind,
  SERVER_TYPES,
  type ServerType,
} from '@/lib/serverconfig/profile';
import { downloadZip, type ZipEntry } from '@/lib/zip';

useHead({ title: 'Server config generator' });

const route = useRoute();
const query = route.query;
const asText = (key: string, fallback: string) => (typeof query[key] === 'string' ? (query[key] as string) : fallback);
const asNumber = (key: string, fallback: number) => {
  const parsed = Number.parseInt(asText(key, ''), 10);
  return Number.isFinite(parsed) && parsed > 0 ? parsed : fallback;
};

const software = ref<Software>(asText('sw', DEFAULT_PROFILE.software) as Software);
const type = ref<ServerType>(asText('type', DEFAULT_PROFILE.type) as ServerType);
const intensity = ref<Intensity>(asText('level', DEFAULT_PROFILE.intensity) as Intensity);
const players = ref(asNumber('players', DEFAULT_PROFILE.players));
const cores = ref(asNumber('cores', DEFAULT_PROFILE.cores));
const worlds = ref(asText('worlds', DEFAULT_PROFILE.worlds) as Profile['worlds']);
const proxy = ref<ProxyKind>(asText('proxy', DEFAULT_PROFILE.proxy) as ProxyKind);
const offlineMode = ref(asText('offline', '') === '1');
const antiCheat = ref(asText('ac', '') === '1');
const customEntities = ref(asText('custom', '') === '1');
const pregenerated = ref(asText('pregen', '') === '1');
const harden = ref(asText('harden', '1') === '1');

const profile = computed<Profile>(() => ({
  software: software.value,
  type: type.value,
  players: Math.min(Math.max(players.value, 1), 2000),
  worlds: worlds.value,
  cores: Math.min(Math.max(cores.value, 1), 128),
  intensity: intensity.value,
  proxy: proxy.value,
  offlineMode: offlineMode.value,
  antiCheat: antiCheat.value,
  customEntities: customEntities.value,
  pregenerated: pregenerated.value,
  harden: harden.value,
}));

const result = computed(() => build(profile.value));
const activeFile = ref('');
const current = computed(() => result.value.files.find(file => file.file.id === activeFile.value));
const selectedType = computed(() => SERVER_TYPES.find(option => option.id === type.value));
const written = computed(() => result.value.files.filter(file => file.changes.length));

const tabs = computed(() =>
  result.value.files.map(file => ({
    id: file.file.id,
    label: file.file.id,
    badge: file.changes.length,
    filename: file.changes.length ? file.file.id : null,
    code: file.text,
    lang: (file.file.format === 'properties' ? 'properties' : 'yaml') as 'properties' | 'yaml',
    empty: `This profile changes nothing in ${file.file.path}. Leave the file as it ships.`,
  })),
);

const optionsHint = computed(() => {
  const on = [
    offlineMode.value && 'offline mode',
    antiCheat.value && 'anti-cheat',
    customEntities.value && 'custom entities',
    pregenerated.value && 'pregenerated',
    harden.value && 'hardening',
  ].filter(Boolean);
  return on.length ? `${on.length} on: ${on.join(', ')}` : 'offline mode, anti-cheat, ItemsAdder, pregenerated world';
});

function readme(): string {
  const worldLabel = { one: 'One', few: 'A few', many: 'Many' }[worlds.value];
  const proxyLabel = { none: 'No', velocity: 'Velocity', bungeecord: 'BungeeCord' }[proxy.value];
  const answers = (
    [
      ['Software', SOFTWARE_LABELS[software.value]],
      ['Server type', selectedType.value?.name],
      ['How far to go', INTENSITIES.find(level => level.id === intensity.value)?.name],
      ['Players at peak', profile.value.players],
      ['CPU cores', profile.value.cores],
      ['Populated worlds', worldLabel],
      ['Behind a proxy', proxyLabel],
    ] as [string, string | number][]
  )
    .map(([name, value]) => `${name.padEnd(17)}${value}`)
    .join('\n  ');

  const warnings = result.value.notices
    .filter(notice => notice.level === 'warning')
    .map(notice => `  * ${notice.title}\n    ${notice.body}`)
    .join('\n\n');

  return [
    'Server configuration generated by https://bxteam.org/tools/server-config',
    `Verified against Minecraft ${VERIFIED_AGAINST}.`,
    '',
    'ANSWERS',
    `  ${answers}`,
    '',
    'WHAT IS IN HERE',
    '  These are partial files. Every key in them is one that should differ from the',
    '  default for this profile; everything else was deliberately left out. Paper,',
    '  Spigot and Bukkit write their own defaults back into a file the first time the',
    '  server starts, so these can be dropped in as they are.',
    '',
    '  Back up your existing configuration first. If a file already exists on the',
    '  server, merge these keys into it rather than replacing it.',
    '',
    'FILES',
    ...written.value.map(file => `  ${file.file.path.padEnd(34)} ${file.changes.length} keys`),
    '',
    'BEFORE YOU START',
    warnings || '  Nothing needs a manual step for this profile.',
    '',
  ].join('\n');
}

function downloadAll() {
  const entries: ZipEntry[] = written.value.map(file => ({ path: file.file.path, text: file.text }));
  entries.push({ path: 'README.txt', text: readme() });
  downloadZip(`${software.value}-${type.value}-config.zip`, entries);
}

watch(
  [
    software,
    type,
    intensity,
    players,
    cores,
    worlds,
    proxy,
    offlineMode,
    antiCheat,
    customEntities,
    pregenerated,
    harden,
  ],
  () => {
    syncQuery({
      sw: software.value,
      type: type.value,
      level: intensity.value,
      players: String(players.value),
      cores: String(cores.value),
      worlds: worlds.value,
      proxy: proxy.value === 'none' ? undefined : proxy.value,
      offline: offlineMode.value ? '1' : undefined,
      ac: antiCheat.value ? '1' : undefined,
      custom: customEntities.value ? '1' : undefined,
      pregen: pregenerated.value ? '1' : undefined,
      harden: harden.value ? undefined : '0',
    });
  },
  { flush: 'post' },
);

const SOFTWARE_OPTIONS = (['paper', 'purpur', 'divinemc'] as Software[]).map(id => ({
  value: id,
  label: SOFTWARE_LABELS[id],
}));
</script>

<template>
	<ToolsToolPage
		title="Server config generator"
		lead="Say what the server is and what it runs on. You get back the keys that should differ from the defaults, in every config file your server software has, each one carrying the reason it moved. Paths and shipped defaults are read straight out of the upstream sources."
	>
		<section class="setup">
			<div class="choice" role="radiogroup" aria-label="Server type">
				<button
					v-for="option in SERVER_TYPES"
					:key="option.id"
					type="button"
