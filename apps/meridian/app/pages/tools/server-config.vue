			</div>
			<p class="choice-sum">{{ selectedType?.blurb }}</p>

			<div class="bar">
				<ToolsSegmentedControl v-model="software" label="Software" :options="SOFTWARE_OPTIONS" />
				<ToolsSegmentedControl
					v-model="intensity"
					label="How far to go"
					:options="INTENSITIES.map(level => ({ value: level.id, label: level.name, hint: level.blurb }))"
				/>
				<div class="field">
					<label class="label" for="players">Players at peak</label>
					<input id="players" v-model.number="players" class="input" type="number" min="1" max="2000" />
				</div>
				<div class="field">
					<label class="label" for="cores">CPU cores</label>
					<input id="cores" v-model.number="cores" class="input" type="number" min="1" max="128" />
				</div>
				<ToolsSegmentedControl
					v-model="worlds"
					label="Populated worlds"
					:options="[
						{ value: 'one', label: 'One' },
						{ value: 'few', label: 'A few' },
						{ value: 'many', label: 'Many' },
					]"
				/>
				<ToolsSegmentedControl
					v-model="proxy"
					label="Behind a proxy"
					:options="[
						{ value: 'none', label: 'No' },
						{ value: 'velocity', label: 'Velocity' },
						{ value: 'bungeecord', label: 'Bungee' },
					]"
				/>
			</div>

			<ToolsMoreOptions :hint="optionsHint">
				<div class="switches">
					<label class="check">
						<input v-model="offlineMode" type="checkbox" />
						<span>Offline mode, no Mojang authentication</span>
					</label>
					<label class="check">
						<input v-model="antiCheat" type="checkbox" />
						<span>An anti-cheat plugin is installed</span>
					</label>
					<label class="check">
						<input v-model="customEntities" type="checkbox" />
						<span>ItemsAdder, ModelEngine or Oraxen</span>
					</label>
					<label class="check">
						<input v-model="pregenerated" type="checkbox" />
						<span>World is pregenerated with a border</span>
					</label>
					<label class="check">
						<input v-model="harden" type="checkbox" />
						<span>Add packet and item limits</span>
					</label>
				</div>
			</ToolsMoreOptions>
		</section>

		<ToolsCodeOutput v-model:active="activeFile" :tabs="tabs" tall>
			<template #rail>
				<div class="rail-total">
					<strong>{{ result.changed }}</strong> keys in {{ written.length }} files
				</div>
				<button type="button" class="rail-zip" @click="downloadAll">
					<Download :size="13" :stroke-width="1.8" />
					<span>All as .zip</span>
				</button>
			</template>
		</ToolsCodeOutput>

		<div class="meta">
			<span v-if="current">Goes in <code>{{ current.file.path }}</code></span>
			<a v-if="current" :href="current.file.reference" target="_blank" rel="noopener">Reference</a>
			<span class="grow" />
			<span>Verified against Minecraft {{ VERIFIED_AGAINST }}</span>
		</div>

		<div class="under">
			<section v-if="current" class="col">
				<h2>What changed</h2>
				<p class="lead">{{ current.file.blurb }}</p>
				<ToolsChangeList v-if="current.changes.length" :changes="current.changes" />
				<p v-else class="empty">
					Nothing in this file needs to change for this profile. The shipped defaults are already the right answer.
				</p>
			</section>

			<aside class="col">
				<h2>Notes</h2>
				<p class="lead">What the answers above did to the result, and what it quietly assumes.</p>
				<ToolsNoticeList :notices="result.notices" />
			</aside>
		</div>
	</ToolsToolPage>
</template>

